    'my_indicator_name = "[Default] Divergence for Many Indicators v4"\n'
    "my_indicator_description = (\n"
    '    "Causal regular and hidden bullish/bearish divergence detection across "\n'
    '    "multiple momentum and volume indicators."\n'
