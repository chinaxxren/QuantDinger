    'recent_low = df["low"].astype(float).shift(1).rolling(struct_len, min_periods=struct_len).min().to_numpy()\n'
    "structure_field = np.where(close_v > recent_high, 1.0, np.where(close_v < recent_low, -1.0, 0.0))\n"
