    "regime = ema(raw_regime, 3)\n"
    "chop_penalty = chop * 0.085\n"
    "vol_penalty = clamp(vol_deviation * 0.04, 0.0, 0.06)\n"
    "dynamic_gate = 0.22 + sensitivity * 0.12 + chop_penalty + vol_penalty\n"
