    "bear_votes = fast_bear.astype(int) + mid_bear.astype(int) + slow_bear.astype(int)\n"
    "required_votes = np.where(chop > 0.70, 3, 2)\n"
    "bull_st_confirmed = bull_votes >= required_votes\n"
    "bear_st_confirmed = bear_votes >= required_votes\n"
